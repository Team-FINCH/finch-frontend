/**
 * 서비스 30종목의 기업 로고.
 *
 * 목록의 종목 자리에 이니셜 뱃지(`shared/ui/StockInitialBadge`) 대신 그 기업의
 * 로고를 그린다. 파일은 `public/brand/stocks/<종목코드>.svg` 에 있다.
 *
 * ## 왜 이제 와서 로고인가
 *
 * FINCH-261 이 이니셜 뱃지에 색을 넣을 때 **종목별 자산을 손으로 박는 길을
 * 한 번 접었다.** 근거는 그때 시드가 300종목이라 "여섯 개만 색이 붙고 나머지는
 * 회색" 이 되는 것이었다. 그래서 종목코드를 해시해 다섯 색 중 하나를 고르는
 * 자동 배정으로 갔다.
 *
 * **그 전제가 바뀌었다.** `finch.universe.enabled: true` 이후 서비스에 존재하는
 * 종목은 30개로 닫혀 있다 — 목록 밖은 검색에서 빠지고 상세·시세·주문·관심
 * 등록이 `STOCK_NOT_FOUND` 다. 30개면 전부 손으로 채울 수 있고, 얼룩덜룩해질
 * 나머지가 없다. 이니셜 한 글자보다 로고가 훑을 때 훨씬 빨리 걸린다.
 *
 * ## 목록은 백엔드 설정이 정본이다
 *
 * 여기 30개는 `backend/src/main/resources/application.yaml` 의
 * `finch.universe.codes`(2026-09-14 확정)를 그대로 옮긴 것이다. **정본은 저쪽이고
 * 여기는 사본이다.** 서비스 종목이 바뀌면 저기를 고친 뒤 여기 목록과 SVG 파일을
 * 같이 맞춘다. 어긋나도 화면이 깨지지는 않는다 — 빠진 종목은 이니셜 뱃지로
 * 돌아갈 뿐이다(`StockLogo` 의 폴백).
 *
 * 프론트가 이 목록으로 **종목의 존재 여부를 판단하지 않는다.** 이건 "로고 파일이
 * 있는 코드" 일 뿐이고, 서비스 종목인지 아닌지는 서버만 안다.
 *
 * ## 로고 파일에 대하여
 *
 * 40x40 원형 SVG 한 벌이다. 원 안쪽이 기업 고유색이고, 흰 바탕 로고(한미반도체·
 * 에코프로 등)가 흰 카드 위에서 사라지지 않도록 바깥에 5% 검정 테두리 링이 들어
 * 있다 — 30개 전부 같은 규격이라 목록에서 크기·정렬이 흔들리지 않는다.
 *
 * 기업 로고는 각 사의 상표다. 모의 투자 서비스가 종목을 식별하려고 쓰는 용도로,
 * 변형 없이 원본 그대로 넣었다.
 */

