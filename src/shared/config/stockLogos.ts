/**
 * 서비스 30종목의 기업 로고.
 *
 * 목록의 종목 자리에 이니셜 뱃지(`shared/ui/StockInitialBadge`) 대신 그 기업의
 * 로고를 그린다. 파일은 `public/brand/stocks/<종목코드>.svg` 에 있다.
 *
 * ## 왜 이제 와서 로고인가
 *
 * FINCH-261 이 이니셜 뱃지에 색을 넣을 때 **종목별 자산을 손으로 박는 길을
 * 한 번 접었다.** 근거는 그때 시드가 300종목이라 "여섯 개만 색이 붙고 나머지는
 * 회색" 이 되는 것이었다. 그래서 종목코드를 해시해 다섯 색 중 하나를 고르는
 * 자동 배정으로 갔다.
 *
 * **그 전제가 바뀌었다.** `finch.universe.enabled: true` 이후 서비스에 존재하는
 * 종목은 30개로 닫혀 있다 — 목록 밖은 검색에서 빠지고 상세·시세·주문·관심
 * 등록이 `STOCK_NOT_FOUND` 다. 30개면 전부 손으로 채울 수 있고, 얼룩덜룩해질
 * 나머지가 없다. 이니셜 한 글자보다 로고가 훑을 때 훨씬 빨리 걸린다.
 *
 * ## 목록은 백엔드 설정이 정본이다
 *
 * 30개의 정본은 `backend/src/main/resources/application.yaml` 의
 * `finch.universe.codes`(2026-09-14 확정)이고, 프론트 사본은
 * `shared/config/serviceStocks.ts` 한 곳이다. **이 파일은 그 사본에서 코드만
 * 파생시킨다** — 전에는 같은 30개를 여기에 손으로 한 벌 더 적어 두었다.
 * 서비스 종목이 바뀌면 백엔드를 고친 뒤 `serviceStocks.ts` 와 SVG 파일을 맞춘다.
 * 어긋나도 화면이 깨지지는 않는다 — 빠진 종목은 이니셜 뱃지로 돌아갈 뿐이다
 * (`StockLogo` 의 폴백).
 *
 * **파생시켰다고 두 개념이 같아진 것은 아니다.** 이쪽은 "로고 파일이 있는 코드" 고
 * 저쪽은 "서비스 종목" 이다. 오늘 두 목록이 같은 이유는 30개 SVG 를 전부 채웠기
 * 때문이다. 종목이 늘었는데 SVG 를 아직 안 그린 순간에는 갈라지므로, 그때는 파생을
 * 풀고 실제로 파일이 있는 코드만 여기 남긴다.
 *
 * 프론트가 이 목록으로 **종목의 존재 여부를 판단하지 않는다.** 서비스 종목인지
 * 아닌지는 서버만 안다.
 *
 * ## 로고 파일에 대하여
 *
 * 40x40 원형 SVG 한 벌이다. 원 안쪽이 기업 고유색이고, 흰 바탕 로고(한미반도체·
 * 에코프로 등)가 흰 카드 위에서 사라지지 않도록 바깥에 5% 검정 테두리 링이 들어
 * 있다 — 30개 전부 같은 규격이라 목록에서 크기·정렬이 흔들리지 않는다.
 *
 * 기업 로고는 각 사의 상표다. 모의 투자 서비스가 종목을 식별하려고 쓰는 용도로,
 * 변형 없이 원본 그대로 넣었다.
 */

import { SERVICE_STOCK_CODES } from './serviceStocks';

/**
 * 로고 SVG 가 있는 종목코드. 30개.
 *
 * **Set 으로 두는 이유** — 목록 한 행마다 조회하는 값이라 `includes` 의 선형
 * 탐색을 30번 곱하고 싶지 않다. 그보다 중요한 건 **없는 코드로 `<img>` 를 그리지
 * 않는 것**이다. 보유·거래내역에는 서비스 종목 밖의 코드가 남아 있을 수 있고
 * (상장폐지·유니버스 개편), 그때 404 를 한 번 쏘고 깨진 이미지가 잠깐 보였다가
 * 폴백되는 것보다 처음부터 이니셜 뱃지를 그리는 쪽이 낫다.
 */
export const STOCK_LOGO_CODES: ReadonlySet<string> = new Set(
  SERVICE_STOCK_CODES,
);

/**
 * 로고 파일 경로. `public/` 아래라 번들러를 거치지 않고 이 문자열 그대로 나간다
 * (`/brand/finch-logo.png` 와 같은 방식).
 *
 * 경로를 조립하는 자리가 여기 하나여야 `STOCK_LOGO_CODES` 와 파일 이름 규칙이
 * 같이 움직인다.
 */
export function stockLogoUrl(stockCode: string): string {
  return `/brand/stocks/${stockCode}.svg`;
}
