/**
 * AI 쿼리를 메모리에서 버리기까지의 시간. AI 쿼리 훅 여섯이 같은 값을 쓴다
 * (`docs/frontConvention.md` §5 "AI 응답 처리 방침").
 *
 * **`gcTime` 은 `staleTime` 과 다른 시계다.** `staleTime` 은 값을 낡았다고 보는
 * 시점이고, `gcTime` 은 그 쿼리를 보는 화면이 하나도 없어진 뒤부터 센다. 화면에
 * 떠 있는 동안은 돌지 않는다.
 *
 * 정하지 않으면 TanStack 기본 5분이 먹는데, 그것이 AI 훅의 `staleTime` 5분과 같다.
 * 두 값이 같으면 "낡았지만 일단 보여주고 뒤에서 갱신" 구간이 통째로 사라진다 —
 * 낡는 순간이 곧 버려지는 순간이라 5분을 넘기면 빈 화면부터 다시 그린다.
 * 그래서 `staleTime` 의 여섯 배로 잡았다.
 *
 * 30분인 근거는 화면을 떠났다 돌아오는 간격이다 — 종목 상세 탭 왕복 1~2분,
 * 포트폴리오 4탭 수십 초, 홈은 탭바 왕복 수 분이라 셋을 다 덮는다. 비용은
 * 메모리뿐이고 AI 응답 JSON 몇 개라 무겁지 않다.
 *
 * 전역 기본값(`queryClient.ts`)에 두지 않았다. 거기에 두면 시세처럼 종목마다 키가
 * 갈라지는 쿼리까지 30분씩 메모리를 쥔다.
 */
export const AI_GC_TIME_MS = 30 * 60_000;
