/**
 * 종목 자리의 치수. `StockLogo` 와 `StockInitialBadge` 가 같이 쓴다.
 *
 * **두 컴포넌트가 같은 자리를 번갈아 쓴다.** 로고가 있는 종목이면 로고가, 없으면
 * 이니셜 뱃지가 그 자리에 선다. 크기가 어긋나면 폴백되는 행만 목록에서
 * 들쭉날쭉해지므로 값은 한 곳에 있어야 한다.
 *
 * 컴포넌트 파일이 아니라 여기 있는 이유는 린트 규약이다 —
 * `react-refresh/only-export-components` 가 컴포넌트 파일에서 상수를 내보내지
 * 못하게 한다(HMR 이 깨진다).
 *
 * **이름이 크기 계단이 아니라 자리 이름인 이유** (FINCH-299). 처음엔 `md`·`sm`
 * 둘뿐이라 계단처럼 읽혔지만 실제로는 "어느 목록의 행인가" 를 가리키는 값이었다.
 * 36px·32px 이 들어오면서 계단으로 읽으면 `md`(44px)가 가운데가 아니게 되고,
 * 이름을 다시 매기면 `size` 를 생략한 호출부(기본값 `md`)가 조용히 줄어든다.
 * 그래서 기존 두 키를 그대로 두고 자리 이름으로 늘렸다.
 */
export const STOCK_BADGE_BOX_CLASS = {
  /** 44x44 — 주 목록 행. 홈 · 포트폴리오 보유 · 주문 (프로토타입 `.th`) */
  md: 'size-11',
  /** 36x36 — 보조 목록 행. 수익률 분석 종목별 기여 · 온보딩 종목 고르기 */
  sub: 'size-9',
  /** 32x32 — 조밀 목록 행. 아직 적지 않은 종목 · 위키 테제 */
  dense: 'size-8',
  /**
   * 22x22 — 한 줄 안에 이름 · 등락률과 나란히 서는 자리. 브리핑 행 머리.
   * 목록 행 것을 줄여 쓸 수 없다.
   */
  sm: 'size-5.5',
} as const;

export type StockBadgeSize = keyof typeof STOCK_BADGE_BOX_CLASS;
